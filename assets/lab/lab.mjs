import {createPreference} from '../runtime/motion-runtime.mjs';
import {mountPress} from '../patterns/press.mjs';
import {mountIconState} from '../patterns/icon-state.mjs';
import {mountNavigation} from '../patterns/navigation.mjs';
import {mountAnchoredDetail} from '../patterns/anchored-detail.mjs';
import {mountIdentityList} from '../patterns/identity-list.mjs';
import {mountDataChart} from '../patterns/data-chart.mjs';
import {mountGroupEntry} from '../patterns/group-entry.mjs';
import {mountBrandMagnet} from '../patterns/brand-magnet.mjs';
import {mountSoftDrag} from '../patterns/soft-drag.mjs';
const $=id=>document.getElementById(id),pref=createPreference(),handles=[];
const checkbox=$('reduce-motion');checkbox.checked=pref.reduced;document.documentElement.dataset.reduced=String(pref.reduced);
pref.subscribe(value=>{document.documentElement.dataset.reduced=String(value);checkbox.checked=value;});
checkbox.addEventListener('change',()=>pref.set(checkbox.checked));
let pressCount=0,brandCount=0;
$('press-button').addEventListener('click',()=>{$('press-count').textContent='完成 '+(++pressCount)+' 次';});
$('magnetic').addEventListener('click',()=>{$('brand-count').textContent='探索 '+(++brandCount)+' 次';});
handles.push(mountPress({button:$('press-button'),face:$('press-face'),pref}));
const heart=mountIconState({button:$('heart-button'),filled:$('heart-fill'),status:$('heart-status'),pref});handles.push(heart);
$('heart-undo').addEventListener('click',()=>heart.set(false));
handles.push(mountNavigation({host:$('nav-host'),tabs:[0,1,2].map(i=>$('tab-'+i)),panels:[0,1,2].map(i=>$('panel-'+i)),indicator:$('nav-indicator'),pref}));
const entries=mountGroupEntry({items:[...document.querySelectorAll('.entry')],pref});handles.push(entries);
$('replay-entry').addEventListener('click',()=>entries.play({replay:true}));
handles.push(mountAnchoredDetail({host:$('detail-host'),surface:$('detail-surface'),image:$('detail-image'),details:$('detail-copy'),toggle:$('detail-toggle'),pref,endpoints:(expanded,host)=>expanded?{x:16,y:12,w:host.clientWidth-32,h:334,artH:210}:{x:16,y:24,w:Math.min(240,host.clientWidth-32),h:266,artH:180}}));
handles.push(mountIdentityList({host:$('tiles'),items:[...document.querySelectorAll('.tile')],filters:[...document.querySelectorAll('[data-filter]')],pref}));
const chart=mountDataChart({bars:[0,1,2].map(i=>$('chart-bar-'+i)),labels:[0,1,2].map(i=>$('chart-value-'+i)),pref});handles.push(chart);
chart.set([30,68,42]);$('chart-a').addEventListener('click',()=>chart.set([30,68,42]));$('chart-b').addEventListener('click',()=>chart.set([80,40,90]));
handles.push(mountBrandMagnet({button:$('magnetic'),visual:$('magnet-visual'),icon:$('magnet-icon'),pref}));
const bubble=mountSoftDrag({button:$('bubble'),shape:$('bubble-shape'),glyph:$('bubble-glyph'),stage:$('bubble-stage'),status:$('bubble-status'),pref});handles.push(bubble);
$('bubble-reset').addEventListener('click',()=>bubble.reset());
$('destroy-patterns').addEventListener('click',()=>{handles.forEach(h=>h.destroy());$('destroy-state').textContent='九个范例控制器已卸载，订阅与观察器已释放。';});
$('copy-prompt').addEventListener('click',async()=>{const field=$('prompt');try{await navigator.clipboard.writeText(field.value);$('copy-state').textContent='已复制';}catch{field.focus();field.select();$('copy-state').textContent='已选中，可直接复制';}});
document.documentElement.dataset.labReady='true';
